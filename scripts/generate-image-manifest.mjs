import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicRoot = path.join(root, "public", "images");
const outputFile = path.join(root, "src", "generated", "image-manifest.ts");
// `postcards` and `extras` back one card each on the location page, so a photo
// dropped in there changes that card alone rather than every slot sharing a
// category. Both fall back to the shared photography while they are empty.
// `stickers` is the cursor-trail artwork rather than photography: every file in
// it joins the trail, so a new landmark is a drop-in with no code change.
const approvedRoots = ["property", "lapu-lapu", "postcards", "extras", "stickers"];
const extensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

const toCaption = (fileName) =>
  path
    .basename(fileName, path.extname(fileName))
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());

async function scanDirectory(directory, relativeParts = []) {
  let entries = [];

  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return [];
    throw error;
  }

  const images = [];

  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith(".") || entry.name.startsWith("_")) continue;

    const absolute = path.join(directory, entry.name);
    const nextParts = [...relativeParts, entry.name];

    if (entry.isDirectory()) {
      images.push(...(await scanDirectory(absolute, nextParts)));
      continue;
    }

    if (!entry.isFile() || !extensions.has(path.extname(entry.name).toLowerCase())) {
      continue;
    }

    const [rootCategory, ...subCategory] = nextParts;
    images.push({
      src: `/images/${nextParts.join("/")}`,
      category: [rootCategory, ...subCategory.slice(0, -1)].join("/"),
      caption: toCaption(entry.name),
      fileName: entry.name,
    });
  }

  return images;
}

const manifest = (
  await Promise.all(
    approvedRoots.map((directory) =>
      scanDirectory(path.join(publicRoot, directory), [directory]),
    ),
  )
)
  .flat()
  .sort((a, b) => a.src.localeCompare(b.src));

const source = `// This file is generated by scripts/generate-image-manifest.mjs.
// Add images under public/images and run npm run images.

export type ImageManifestItem = {
  src: string;
  category: string;
  caption: string;
  fileName: string;
};

export const imageManifest: ImageManifestItem[] = ${JSON.stringify(manifest, null, 2)};
`;

await fs.mkdir(path.dirname(outputFile), { recursive: true });
await fs.writeFile(outputFile, source, "utf8");

console.log(`Generated image manifest with ${manifest.length} image(s).`);
